/**
 * Turn a Praxis name (or a hand-typed slug) into the URL-safe `clinics.slug`:
 * lowercase, German umlauts transliterated, everything else collapsed to "-".
 */
export function slugifyClinicName(input: string): string {
  return input
    .trim()
    .toLowerCase()
    .replace(/ä/g, "ae")
    .replace(/ö/g, "oe")
    .replace(/ü/g, "ue")
    .replace(/ß/g, "ss")
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60)
    .replace(/-+$/g, "");
}
